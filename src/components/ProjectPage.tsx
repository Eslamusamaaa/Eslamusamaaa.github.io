import { useEffect, useState } from "react";
import { Link, useParams } from "react-router-dom";
import { projects, type Project } from "../data";
import { galleries } from "../gallery";
import { asset, usePageMeta } from "../lib";
import { Gallery } from "./Gallery";
import { VideoLink } from "./Work";
import { ArrowIcon, PlayIcon, WaIcon } from "./icons";

function VideoCard({ p }: { p: Project }) {
  const [thumbFailed, setThumbFailed] = useState(false);
  if (!p.video) return null;
  return (
    <a className="video-card" href={p.video.url} target="_blank" rel="noopener noreferrer" aria-label={`Watch on YouTube: ${p.video.title}`}>
      {thumbFailed ? (
        <span className="video-fallback" aria-hidden="true">
          <PlayIcon size={22} />
        </span>
      ) : (
        <span className="video-thumb">
          <img src={`https://i.ytimg.com/vi/${p.video.id}/hqdefault.jpg`} alt="" width={480} height={360} loading="lazy" referrerPolicy="no-referrer" onError={() => setThumbFailed(true)} />
          <span className="play" aria-hidden="true">
            <PlayIcon size={18} />
          </span>
        </span>
      )}
      <span className="video-meta">
        <strong dir="rtl" lang="ar">{p.video.title}</strong>
        <small>Project explanation video · opens YouTube</small>
      </span>
    </a>
  );
}

function Sample({ s }: { s: NonNullable<Project["samples"]>[number] }) {
  const [failed, setFailed] = useState(false);
  return (
    <li>
      <p className="sample-text" dir="rtl" lang="ar">
        {s.text}
      </p>
      {failed ? (
        <p className="fine">This audio file could not be loaded.</p>
      ) : (
        <audio controls preload="none" src={asset(s.src)} onError={() => setFailed(true)}>
          Your browser does not support audio playback.
        </audio>
      )}
      <span className="sample-note">{s.note}</span>
    </li>
  );
}

const sectionsFor = (p: Project) =>
  [
    { id: "overview", label: "Overview" },
    p.samples && { id: "samples", label: "Audio samples" },
    { id: "problem", label: "Problem" },
    { id: "flow", label: "How it works" },
    { id: "implementation", label: "Implementation" },
    galleries[p.slug] && { id: "screenshots", label: "Screenshots" },
    p.challenges.length > 0 && { id: "challenges", label: "Challenges" },
    { id: "results", label: "Results and limits" },
    p.next.length > 0 && { id: "next", label: "Next" },
  ].filter(Boolean) as { id: string; label: string }[];

export default function ProjectPage() {
  const { slug } = useParams();
  const i = projects.findIndex((x) => x.slug === slug);
  const p = projects[i];
  usePageMeta(
    p ? `${p.title} · Eslam Usama` : "Project not found · Eslam Usama",
    p ? p.summary : "This project could not be found.",
    p ? `/projects/${p.slug}` : "/"
  );
  const [current, setCurrent] = useState("overview");

  // Mini table of contents scroll-spy.
  useEffect(() => {
    if (!p) return;
    const els = sectionsFor(p)
      .map((s) => document.getElementById(s.id))
      .filter(Boolean) as HTMLElement[];
    const io = new IntersectionObserver(
      (entries) => {
        const v = entries.filter((e) => e.isIntersecting).sort((a, b) => a.boundingClientRect.top - b.boundingClientRect.top);
        if (v[0]) setCurrent(v[0].target.id);
      },
      { rootMargin: "-20% 0px -65% 0px" }
    );
    els.forEach((e) => io.observe(e));
    return () => io.disconnect();
  }, [p]);

  if (!p)
    return (
      <main id="main" tabIndex={-1} className="wrap page">
        <h1>Project not found</h1>
        <p>
          <Link to="/">Back to all projects</Link>
        </p>
      </main>
    );

  const prev = projects[(i - 1 + projects.length) % projects.length];
  const next = projects[(i + 1) % projects.length];
  const isBots = p.slug === "whatsapp-commerce-bots";

  return (
    <main id="main" tabIndex={-1} className="wrap page">
      <Link to="/" state={{ restore: true }} className="back">
        ← All projects
      </Link>
      <header className="page-head">
        {p.image && <img className="logo-tile" src={asset(p.image.src)} alt={p.image.alt} width={88} height={88} />}
        <div>
          <p className="kicker">{p.kind}</p>
          <h1>{p.title}</h1>
          <p className="lede">{p.summary}</p>
          <p className="status">Status: {p.status}</p>
          {p.video && <VideoLink p={p} />}
        </div>
      </header>

      <div className="page-grid">
        <div className="page-main">
          <section id="overview" aria-labelledby="h-overview">
            <h2 id="h-overview">Overview</h2>
            <p>{p.overview}</p>
            <VideoCard p={p} />
          </section>

          {p.samples && (
            <section id="samples" aria-labelledby="h-samples">
              <h2 id="h-samples">Audio samples</h2>
              <p className="muted">Speech generated by the model, with the Arabic input text, extracted from a recording of my test notebook.</p>
              <ul className="samples">
                {p.samples.map((s) => (
                  <Sample key={s.src} s={s} />
                ))}
              </ul>
              {p.proof && (
                <figure className="proof">
                  <img src={asset(p.proof.src)} alt={p.proof.alt} width={1080} height={420} loading="lazy" />
                  <figcaption>{p.proof.caption}</figcaption>
                </figure>
              )}
            </section>
          )}

          <section id="problem" aria-labelledby="h-problem">
            <h2 id="h-problem">Problem and motivation</h2>
            <p>{p.problem}</p>
          </section>

          <section id="flow" aria-labelledby="h-flow">
            <h2 id="h-flow">{p.flowTitle}</h2>
            <ol className="flow">
              {p.flow.map((s, n) => (
                <li key={s.title}>
                  <span className="n" aria-hidden="true">
                    {n + 1}
                  </span>
                  <strong>{s.title}</strong>
                  <span>{s.note}</span>
                </li>
              ))}
            </ol>
            {p.flowCaveat && <p className="note">{p.flowCaveat}</p>}
            {p.diagram && (
              <figure className="diagram">
                <a href={asset(p.diagram.src)} target="_blank" rel="noopener noreferrer" aria-label="Open the full-size diagram in a new tab">
                  <img src={asset(p.diagram.src)} alt={p.diagram.alt} width={p.diagram.width} height={p.diagram.height} loading="lazy" />
                </a>
                <figcaption>{p.diagram.caption}</figcaption>
              </figure>
            )}
          </section>

          <section id="implementation" aria-labelledby="h-implementation">
            <h2 id="h-implementation">Implementation</h2>
            {p.implementation.map((x) => (
              <div key={x.heading}>
                <h3>{x.heading}</h3>
                <p>{x.body}</p>
              </div>
            ))}
          </section>

          {galleries[p.slug] && (
            <section id="screenshots" aria-labelledby="h-screenshots">
              <h2 id="h-screenshots">Screenshots and analysis</h2>
              <Gallery groups={galleries[p.slug]} idPrefix={p.slug} />
            </section>
          )}

          {p.challenges.length > 0 && (
            <section id="challenges" aria-labelledby="h-challenges">
              <h2 id="h-challenges">Challenges and trade-offs</h2>
              <ul className="bullets">
                {p.challenges.map((c) => (
                  <li key={c.challenge}>
                    <strong>{c.challenge}.</strong> {c.solution}
                  </li>
                ))}
              </ul>
            </section>
          )}

          <section id="results" aria-labelledby="h-results">
            <h2 id="h-results">Results and limitations</h2>
            <ul className="bullets">
              {p.results.map((r) => (
                <li key={r}>{r}</li>
              ))}
              {p.limitations.map((r) => (
                <li key={r} className="limit">
                  {r}
                </li>
              ))}
            </ul>
          </section>

          {p.next.length > 0 && (
            <section id="next" aria-labelledby="h-next">
              <h2 id="h-next">Future improvements</h2>
              <ul className="bullets">
                {p.next.map((r) => (
                  <li key={r}>{r}</li>
                ))}
              </ul>
            </section>
          )}

          <nav className="pager" aria-label="More projects">
            <Link to={`/projects/${prev.slug}`} className="pager-link prev">
              <small>Previous project</small>
              <span>{prev.title}</span>
            </Link>
            <Link to={`/projects/${next.slug}`} className="pager-link next">
              <small>Next project</small>
              <span>
                {next.title} <ArrowIcon size={14} />
              </span>
            </Link>
          </nav>
        </div>

        <aside className="page-aside" aria-label="Project details">
          <nav className="toc" aria-label="On this page">
            <p className="aside-label">On this page</p>
            <ol>
              {sectionsFor(p).map((s) => (
                <li key={s.id}>
                  <a href={`#${s.id}`} aria-current={current === s.id ? "true" : undefined}>
                    {s.label}
                  </a>
                </li>
              ))}
            </ol>
          </nav>
          <p className="callout">
            <strong>My contribution.</strong> {p.contribution}
          </p>
          <h2 className="aside-label">Technologies</h2>
          <dl className="stack">
            {p.stack.map((s) => (
              <div key={s.name}>
                <dt>{s.name}</dt>
                <dd>{s.role}</dd>
              </div>
            ))}
          </dl>
          {(p.links.length > 0 || isBots) && (
            <>
              <h2 className="aside-label">Links</h2>
              <ul className="aside-links">
                {isBots && (
                  <li>
                    <Link to="/" state={{ scrollTo: "demos" }}>
                      <WaIcon size={16} /> Try the live demos
                    </Link>
                  </li>
                )}
                {p.links.map((l) => (
                  <li key={l.href}>
                    {l.href.startsWith("#/") ? (
                      <Link to={l.href.slice(1)}>{l.label}</Link>
                    ) : (
                      <a href={l.href} target="_blank" rel="noopener noreferrer">
                        {l.label} <span className="sr">(opens in a new tab)</span>
                      </a>
                    )}
                  </li>
                ))}
              </ul>
            </>
          )}
        </aside>
      </div>
    </main>
  );
}
